#!/usr/bin/env python3
"""Build a shared, offline stylesheet from the operator's installed fonts."""

import base64
from pathlib import Path


def main():
    directory = Path.home() / ".fonts"
    faces = [
        ("Synonym", "Synonym-Regular.woff2", 400, "normal"),
        ("Synonym", "Synonym-Bold.woff2", 700, "normal"),
        ("CMU Typewriter Text", "Typewriter/cmuntt.woff", 400, "normal"),
        ("CMU Typewriter Text", "Typewriter/cmuntb.woff", 700, "normal"),
        ("CMU Typewriter Text", "Typewriter/cmunit.woff", 400, "italic"),
        ("CMU Typewriter Text", "Typewriter/cmuntx.woff", 700, "italic"),
    ]
    styles = [
        "/* Generated by readme-fonts.py; do not edit.",
        "Synonym: Copyright 2017-2021 Indian Type Foundry. All rights reserved.",
        "License: https://fontshare.com/terms",
        "",
        (directory / "Typewriter/OFL.txt").read_text().strip(),
        "*/",
    ]
    for family, filename, weight, style in faces:
        path = directory / filename
        format_name = path.suffix[1:]
        data = base64.b64encode(path.read_bytes()).decode("ascii")
        styles.append(
            "@font-face {\n"
            f'  font-family: "{family}";\n'
            f"  font-weight: {weight};\n"
            f"  font-style: {style};\n"
            f'  src: url("data:font/{format_name};base64,{data}") '
            f'format("{format_name}");\n'
            "}"
        )
    print("\n".join(styles))


if __name__ == "__main__":
    main()
